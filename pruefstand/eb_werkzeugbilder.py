# Einrichtblatt: Werkzeugbilder bei Langdrehern (1.456.0): im Platzfenster
# einschalten, Werkzeug markieren, auf dem Blatt rot markiert, gespeichert.
import time, os
from pruefstand import server_starten, FAKE, CH, PORT
from playwright.sync_api import sync_playwright
server_starten(); time.sleep(0.4)
fehler = []
BILD = os.environ.get("BILD_ORDNER", ".")
def pruefe(was, ok):
    print(("ok   " if ok else "FEHLER ") + was)
    if not ok: fehler.append(was)
with sync_playwright() as p:
    br = p.chromium.launch(executable_path=CH, args=["--no-sandbox", "--disable-dev-shm-usage"])
    pg = br.new_context(viewport={"width": 1600, "height": 950}).new_page()
    pg.on("pageerror", lambda e: fehler.append("SEITENFEHLER: " + str(e)[:200]))
    pg.route("**/cdn.jsdelivr.net/**", lambda r: r.fulfill(status=200, content_type="application/javascript", body=FAKE))
    for u in ["**://fonts.googleapis.com/**", "**://fonts.gstatic.com/**", "**://esm.sh/**", "**://*.supabase.co/**", "**://api.open-meteo.com/**"]:
        pg.route(u, lambda r: r.abort())
    pg.goto(f"http://127.0.0.1:{PORT}/index.html#planwand", wait_until="domcontentloaded")
    pg.wait_for_selector(".pw-tafel"); pg.wait_for_timeout(1200)
    pg.evaluate("() => { TEST.daten.artikel_bild = []; TEST.daten.eb_bilder = []; }")
    pg.locator("#pw-hoco").click(); pg.wait_for_timeout(1000)
    pg.locator("[data-bereich='10000']").click(); pg.wait_for_timeout(600)
    pg.locator("[data-kunde='10000']").click(); pg.wait_for_timeout(600)
    pg.locator("[data-hoco-auf='10000-0301']").click(); pg.wait_for_timeout(1200)
    pg.click("[data-blatt-neu='t1']"); pg.wait_for_selector("[data-eba-seite]"); pg.wait_for_timeout(500)
    pg.click("[data-platz='T100']"); pg.wait_for_selector("[data-platzfenster='T100']")
    pf = pg.locator("[data-platzfenster='T100']")
    pf.locator("[data-pf='taetigkeit']").click(); pg.keyboard.type("Abstechen")
    pruefe("Langdreher: Häkchen da", pf.locator("[data-pf='wzBilder']").count() == 1)
    pf.locator("[data-pf='wzBilder']").check(); pg.wait_for_timeout(200)
    wz = pg.locator("[data-pf-wzb]")
    pruefe("Bild nicht im Fenster", pf.locator("[data-pf-wzb]").count() == 0 and wz.count() == 1)
    fb, wb = pf.bounding_box(), wz.bounding_box()
    pruefe("Bild auf der anderen Seite", wb["x"] + wb["width"] < fb["x"] or wb["x"] > fb["x"] + fb["width"])
    k = pg.locator("[data-wzb-ziehen]").bounding_box()
    pg.mouse.move(k["x"] + 30, k["y"] + 8); pg.mouse.down(); pg.mouse.move(k["x"] + 230, k["y"] + 158, steps=6); pg.mouse.up()
    wb2 = wz.bounding_box()
    pruefe("Bildfeld verschiebbar", abs(wb2["x"] - wb["x"] - 200) < 3 and abs(wb2["y"] - wb["y"] - 150) < 3)
    pg.mouse.move(k["x"] + 230, k["y"] + 158); pg.mouse.down(); pg.mouse.move(k["x"] + 30, k["y"] + 8, steps=6); pg.mouse.up()
    wz.locator("[data-wzb-ziel='2-4']").click(); pg.wait_for_timeout(200)
    pruefe("Markierung im Fenster", wz.locator("[data-eba-wzb='2-4'] rect[stroke]").count() == 1)
    # Schieben mit Pfeil und Ziehen, Farbe wählen (1.457.0)
    wz.locator("[data-wzb-schieben='rechts']").click(); wz.locator("[data-wzb-schieben='rechts']").click()
    pruefe("Pfeil schiebt", wz.locator("[data-eba-wzb='2-4']").get_attribute("data-wzb-versatz") == "2,0")
    bx = wz.locator("[data-wzb-marke]").bounding_box()
    pg.mouse.move(bx["x"] + bx["width"] / 2, bx["y"] + bx["height"] / 2); pg.mouse.down()
    pg.mouse.move(bx["x"] + bx["width"] / 2 - 10, bx["y"] + bx["height"] / 2 + 5, steps=5); pg.mouse.up(); pg.wait_for_timeout(200)
    v = wz.locator("[data-eba-wzb='2-4']").get_attribute("data-wzb-versatz") if wz.locator("[data-eba-wzb='2-4']").count() else "weg"
    print("nach Ziehen", v)
    pruefe("Ziehen schiebt", v not in ("2,0", "weg"))
    pruefe("Keine eigene Farbwahl", wz.locator("[data-wzb-farbe-wahl]").count() == 0)
    wz.locator("[data-wzb-mitte]").click(); pg.wait_for_timeout(100)
    pg.locator("[data-eba-schriftzeile] [data-pf-geofarbe='#1f5fd6']").click(); pg.wait_for_timeout(200)
    pruefe("Farbe blau", wz.locator("[data-wzb-marke]").get_attribute("stroke") == "#1f5fd6")
    pg.screenshot(path=os.path.join(BILD, "eb_wzb_fenster.png"))
    pf.locator("[data-pf-ok]").click(); pg.wait_for_timeout(300)
    pruefe("Auf dem Blatt markiert", pg.locator("[data-platz='T100'] [data-eba-wzb='2-4']").count() == 1)
    pg.click("[data-eba-speichern]"); pg.wait_for_timeout(1000)
    b = pg.evaluate("TEST.daten.einrichtblatt_app.find(b => b.hoco_nr === '10000-0301')")
    t = b and b["plaetze"].get("T100", {})
    print(t)
    pruefe("Gespeichert", t.get("wzBilder") is True and t.get("wzMarke") == "2-4" and t.get("wzFarbe") == "#1f5fd6")
    pruefe("Blatt blau", pg.locator("[data-platz='T100'] [data-wzb-marke]").get_attribute("stroke") == "#1f5fd6")
    pruefe("Nach Speichern sichtbar", pg.locator("[data-platz='T100'] [data-eba-wzb='2-4'] image").count() == 1)
    pg.locator("[data-platz='T100']").screenshot(path=os.path.join(BILD, "eb_wzb_platz.png"))
    pg.screenshot(path=os.path.join(BILD, "eb_wzb_blatt.png"))
    # Abwählen: nochmals antippen nimmt die Markierung weg
    pg.click("[data-eba-bearbeiten]"); pg.wait_for_timeout(500)
    pg.click("[data-platz='T100']"); pg.wait_for_selector("[data-platzfenster='T100']")
    pg.locator("[data-pf-wzb] [data-wzb-marke]").click(); pg.wait_for_timeout(200)
    pruefe("Abwählen", pg.locator("[data-pf-wzb] rect[stroke]").count() == 0)
    br.close()
print("Fehler:", fehler or "keine")
